// Netlify build step: bundle the plan page and browser adapter into src/assets.gen.js so the Netlify Function can
// serve them (a function cannot read the site's files at run time). Run by Netlify via netlify.toml.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const page = await readFile(path.join(root, 'public', 'plan.html'), 'utf8');
const adapter = await readFile(path.join(root, 'public', 'adapter.js'), 'utf8');
const out = `// Generated by scripts/build-netlify.mjs at build time. Do not edit.\nexport const PAGE_HTML = ${JSON.stringify(page)};\nexport const ADAPTER_JS = ${JSON.stringify(adapter)};\n`;
await writeFile(path.join(root, 'src', 'assets.gen.js'), out, 'utf8');
console.log(`Bundled plan.html (${Math.round(page.length / 1024)} KB) and adapter.js (${Math.round(adapter.length / 1024)} KB) into src/assets.gen.js`);
